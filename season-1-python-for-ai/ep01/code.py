# My first Python program - Code with me, Episode 1
# Run it by typing:  python hello.py

# print() shows a message on the screen.
# Anything inside the quotes is called a "string" - it's just text.
print("Hello! I'm your computer, and I can finally talk.")

# input() asks YOU a question and waits for your answer.
# Your answer gets stored in a "variable" called name.
name = input("What's your name? ")

# The + sign joins pieces of text together.
print("Nice to meet you, " + name + "!")
print("You just wrote your first program. Day 1 of 30 - let's go!")
